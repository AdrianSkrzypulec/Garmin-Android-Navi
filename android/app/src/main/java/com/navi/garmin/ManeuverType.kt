package com.navi.garmin

/**
 * Normalized turn-by-turn maneuver types corresponding to Garmin watch vector graphics.
 */
enum class ManeuverType {
    STRAIGHT,
    TURN_LEFT,
    TURN_RIGHT,
    SLIGHT_LEFT,
    SLIGHT_RIGHT,
    SHARP_LEFT,
    SHARP_RIGHT,
    U_TURN,
    ROUNDABOUT,
    KEEP_LEFT,
    KEEP_RIGHT,
    DESTINATION,
    NONE
}

